var REPO = (function() {
  var h = location.hostname, p = location.pathname;
  if (!/\.github\.io$/.test(h)) return null;
  var owner = h.replace(/\.github\.io$/, '');
  var seg = p.split('/').filter(Boolean);
  return owner + '/' + (seg.length ? seg[0] : (owner + '.github.io'));
})();

