var PAGE_DIR = (function() {
  var p = location.pathname || '/';
  var i = p.lastIndexOf('/');
  var last = p.substring(i + 1);
  if (last.indexOf('.') >= 0) p = p.substring(0, i + 1);
  if (p.charAt(p.length - 1) !== '/') p += '/';
  return p;
})();

